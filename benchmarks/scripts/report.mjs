#!/usr/bin/env node
// Turns results/*.json into results/summary.md, which the docs site includes on its
// benchmarks page. Run after the benchmarks; the numbers are never edited by hand.
//
//   node scripts/report.mjs

import { readFileSync, writeFileSync } from 'node:fs'

const load = (name) => JSON.parse(readFileSync(new URL(`../results/${name}.json`, import.meta.url), 'utf8'))
const core = load('core')
const browser = load('browser')
const size = load('size')

const lines = []
const table = (header, rows) => {
  lines.push(`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`)
  for (const row of rows)
    lines.push(`| ${row.map((cell) => (cell === null || cell === undefined ? '' : String(cell))).join(' | ')} |`)
  lines.push('')
}

lines.push(
  `<!-- Generated by benchmarks/scripts/report.mjs from results/*.json. Do not edit by hand. -->`,
  '',
  `### Streams`,
  '',
  `smooth-stream-text ${core.meta.versions['smooth-stream-text']} built from \`${core.meta.build}\`${core.meta.build.endsWith('-dirty') ? ' (includes changes not yet released; see the changelog)' : ''}, AI SDK \`ai\` ${core.meta.versions.ai}, ${core.meta.date}.`,
  '',
)
table(
  ['Stream', 'Origin', 'Characters', 'Chunks', 'Duration', 'Pattern'],
  core.meta.traces.map((t) => [
    t.name,
    t.synthetic ? 'synthetic' : 'recorded',
    t.chars,
    t.chunks,
    `${(t.durationMs / 1000).toFixed(1)} s`,
    t.description ?? t.source,
  ]),
)

const approaches = [...new Set(core.results.map((r) => r.approach))]
const recorded = core.meta.traces.filter((t) => !t.synthetic)

lines.push(
  '### Recorded streams',
  '',
  'Real model output as it reached the client. Lag is the time from a character arriving to it being visible. Evenness is the coefficient of variation of characters added per 100 ms while the answer appears: lower is more even. Largest step is the most characters that appeared in one frame. Pauses are gaps of more than 250 ms without new text before the answer is complete. Broken frames end with an unclosed Markdown construct on the last line; split frames end inside a grapheme cluster.',
  '',
)
for (const trace of recorded) {
  lines.push(
    `**${trace.name}**: ${trace.chars} characters in ${trace.chunks} chunks over ${(trace.durationMs / 1000).toFixed(1)} s.`,
    '',
  )
  table(
    [
      'Approach',
      'First text (ms)',
      'Lag p50 (ms)',
      'Lag p95 (ms)',
      'Tail (ms)',
      'Evenness',
      'Largest step',
      'Pauses',
      'Broken frames',
      'Split frames',
    ],
    core.results
      .filter((r) => r.trace === trace.name)
      .map((r) => [
        r.approach,
        r.firstVisibleMs,
        r.lagP50Ms,
        r.lagP95Ms,
        r.tailMs,
        r.evenness,
        r.largestStepChars,
        r.visiblePauses,
        r.brokenMarkdownFrames,
        r.splitGraphemeFrames,
      ]),
  )
}

lines.push(
  '### Text integrity across all streams',
  '',
  'Totals over all eleven streams. Every approach delivered the complete text, and every frame was a prefix of it.',
  '',
)
table(
  ['Approach', 'Frames with broken Markdown', 'Frames splitting a grapheme cluster', 'Complete text'],
  approaches.map((approach) => {
    const rows = core.results.filter((r) => r.approach === approach)
    return [
      approach,
      rows.reduce((n, r) => n + r.brokenMarkdownFrames, 0),
      rows.reduce((n, r) => n + r.splitGraphemeFrames, 0),
      rows.every((r) => r.complete && r.prefixViolations === 0) ? 'all streams' : 'no',
    ]
  }),
)

lines.push('### Synthetic scenarios', '', 'Each scenario stresses one pattern. Open a row for the full table.', '')
for (const trace of core.meta.traces.filter((t) => t.synthetic)) {
  lines.push(`<details><summary>${trace.name}: ${trace.description}</summary>`, '')
  table(
    [
      'Approach',
      'First text',
      'Lag p50',
      'Lag p95',
      'Lag max',
      'Tail',
      'Evenness',
      'Largest step (chars)',
      'Pauses',
      'Broken MD',
      'Split',
    ],
    core.results
      .filter((r) => r.trace === trace.name)
      .map((r) => [
        r.approach,
        r.firstVisibleMs,
        r.lagP50Ms,
        r.lagP95Ms,
        r.lagMaxMs,
        r.tailMs,
        r.evenness,
        r.largestStepChars,
        r.visiblePauses,
        r.brokenMarkdownFrames,
        r.splitGraphemeFrames,
      ]),
  )
  lines.push('</details>', '')
}

lines.push(
  '### Rendering cost in a browser',
  '',
  `${browser.meta.browser}, ${browser.meta.machine}, ${browser.meta.date}. Streams replayed in real time; Markdown rendered with marked into \`innerHTML\`. Renders and render time count calls to the Markdown renderer (or appends for plain text). Peak elements is the most elements inside the output at once; with the reveal these are the spans still animating.`,
  '',
)
table(
  ['Stream', 'Approach', 'Renders', 'Render time (ms)', 'Long tasks', 'Frame p95 (ms)', 'Peak elements'],
  browser.results.map((r) => [
    r.trace,
    r.approach,
    r.renders ?? 'n/a',
    r.renderMsTotal ?? 'n/a',
    r.longTasks,
    r.frameP95Ms,
    r.maxElements,
  ]),
)

lines.push(
  '### Bundle size',
  '',
  `smooth-stream-text ${size.meta.version}, ${size.meta.bundler}, ${size.meta.date}.`,
  '',
)
table(
  ['Import', 'Minified', 'gzip', 'brotli'],
  size.results.map((r) => [
    r.name,
    `${(r.minBytes / 1024).toFixed(1)} kB`,
    `${(r.gzipBytes / 1024).toFixed(1)} kB`,
    `${(r.brotliBytes / 1024).toFixed(1)} kB`,
  ]),
)

writeFileSync(new URL('../results/summary.md', import.meta.url), lines.join('\n'))
console.log('wrote results/summary.md')
